export function resolveTourBusCity(input) {
  const bit = String(input || '')
    .split(/[·,/]/)[0]
    .trim()
  if (!bit) return ''
  if (TOUR_BUS_CITY_ALIASES[bit]) return TOUR_BUS_CITY_ALIASES[bit]
  const lower = bit.toLowerCase()
  if (TOUR_BUS_CITY_ALIASES[lower]) return TOUR_BUS_CITY_ALIASES[lower]
  if (bit.includes('서울')) return 'kr-seoul'
  if (bit.includes('부산')) return 'kr-busan'
  if (bit.includes('경주')) return 'kr-gyeongju'
  if (bit.includes('전주')) return 'kr-jeonju'
  if (bit.includes('제주')) return 'kr-jeju'
  if (bit.includes('동해')) return 'kr-donghae'
  if (bit.includes('묵호')) return 'kr-donghae'
  return ''
}

