import type { Trip, TripItem } from '../types'
import { addDays, todayIso } from '../lib/dates'
import { uid as makeId } from '../lib/id'

function uid(prefix: string): string {
  return `${prefix}-${Math.random().toString(36).slice(2, 9)}`
}

function item(
  partial: Omit<TripItem, 'id'> & { id?: string },
): TripItem {
  return { id: partial.id ?? uid('item'), ...partial }
}

export function cloneDemo(): Trip {
  const base = demoTrip()
  return {
    ...base,
    id: makeId('trip'),
    items: base.items.map((entry) => ({ ...entry, id: makeId('item') })),
    updatedAt: new Date().toISOString(),
  }
}

export function emptyTrip(): Trip {
  const start = todayIso()
  return {
    id: uid('trip'),
    title: '새로운 여행',
    destination: '',
    startDate: start,
    endDate: addDays(start, 3),
    adults: 2,
    children: 0,
    items: [],
  }
}

